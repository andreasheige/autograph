import pytest

from src.agents.daily_note_retrofit import DailyNoteRetrofitAgent
from src.core.daily_note_renderer import render_daily_note, retrofit_daily_note
from src.core.vocabulary import ConceptIndex

VOCABULARY = """# Vocabulary

- [x] bff; alt: backend-for-frontend
- [x] entra
- [x] kubernetes; alt: k8s
"""

OLD_NOTE = """# Daily Journal: 2026-08-17

## Day summary
Worked on login.

## Technical notes

### BFF login on k8s

**What was done**
Wired Entra into the BFF.

**What went well**
Nothing broke.

**What we learned**
Not recorded.

**Worth remembering**
Not recorded.

### Shell cleanup

**What was done**
Fixed zshrc.

**What went well**
Not recorded.

**What we learned**
Not recorded.

**Worth remembering**
Not recorded.

## Related notes
- [[daily_notes/2026-08-18|2026-08-18]]


## Connected graph
- **Agents:** [[agents/Ollama|Ollama]], [[agents/Pi|Pi]]
- **Commits:**
  - [[projects/web/commits/abc123def456|abc123def456 Add login]]
---
*Generated by Autograph Agent*
"""


def concepts(tmp_path):
    (tmp_path / "vocabulary.md").write_text(VOCABULARY, encoding="utf-8")
    folder = tmp_path / "wiki" / "concepts"
    folder.mkdir(parents=True)
    (folder / "bff-login.md").write_text(
        '---\ntitle: "BFF login"\ntags: [bff, entra]\n---\n', encoding="utf-8"
    )
    return ConceptIndex.load(tmp_path)


def test_retrofit_reads_properties_back_from_an_old_note(tmp_path):
    content = retrofit_daily_note(OLD_NOTE, "2026-08-17", concepts(tmp_path).annotate)

    assert content.startswith(
        '---\ntype: "daily-note"\ndate: 2026-08-17\nprojects: ["web"]\n'
        'agents: ["Pi"]\nmodels: []\ncommits: 1\n'
        'tags: ["bff", "entra", "kubernetes"]\ngenerated_by: "autograph"\n---\n\n'
        "# Daily Journal: 2026-08-17\n"
    )
    assert (
        "Not recorded.\n\n**Related wiki:** [[wiki/concepts/bff-login|BFF login]]\n\n"
        "### Shell cleanup" in content
    )
    assert content.count("**Related wiki:**") == 1
    assert content.endswith("---\n*Generated by Autograph Agent*\n")


def test_retrofit_is_idempotent_and_refreshes_after_vocabulary_edits(tmp_path):
    index = concepts(tmp_path)
    once = retrofit_daily_note(OLD_NOTE, "2026-08-17", index.annotate)

    assert retrofit_daily_note(once, "2026-08-17", index.annotate) == once

    (tmp_path / "vocabulary.md").write_text("# Vocabulary\n", encoding="utf-8")
    emptied = retrofit_daily_note(once, "2026-08-17", ConceptIndex.load(tmp_path).annotate)
    assert "tags: []" in emptied
    assert "**Related wiki:**" not in emptied
    assert emptied == retrofit_daily_note(OLD_NOTE, "2026-08-17", ConceptIndex.load(tmp_path).annotate)


def test_retrofit_matches_a_freshly_rendered_note(tmp_path):
    index = concepts(tmp_path)
    section = {
        "title": "BFF login on k8s",
        "work_done": "Wired Entra into the BFF.",
        "project": "web",
        "source": "claude",
        "session_id": "abc-1",
        "models": ["claude-opus-5-5"],
        "commits": ["abc123def456"],
    }
    index.annotate(section)
    rendered = render_daily_note(
        "2026-10-22",
        "Summary.",
        [section],
        [{"id": "abc123def456", "title": "Add login", "project": "web"}],
        ["2026-10-21"],
    )

    assert retrofit_daily_note(rendered, "2026-10-22", index.annotate) == rendered


def test_retrofit_refuses_frontmatter_it_did_not_write(tmp_path):
    with pytest.raises(ValueError):
        retrofit_daily_note("---\ntitle: mine\n---\n\n" + OLD_NOTE, "2026-08-17", concepts(tmp_path).annotate)


def test_agent_skips_manual_notes(tmp_path):
    concepts(tmp_path)
    notes = tmp_path / "daily_notes"
    notes.mkdir()
    (notes / "2026-08-17.md").write_text(OLD_NOTE, encoding="utf-8")
    (notes / "Index.md").write_text("# Daily notes\n", encoding="utf-8")

    assert DailyNoteRetrofitAgent(tmp_path).run(sync=False) == 1
    assert (notes / "Index.md").read_text(encoding="utf-8") == "# Daily notes\n"
    assert DailyNoteRetrofitAgent(tmp_path).run(sync=False) == 0


def test_agent_keeps_carriage_returns_in_prose(tmp_path):
    concepts(tmp_path)
    notes = tmp_path / "daily_notes"
    notes.mkdir()
    note = notes / "2026-08-17.md"
    note.write_bytes(OLD_NOTE.replace("Fixed zshrc.", "Fixed `\r\n` in zshrc.").encode())

    DailyNoteRetrofitAgent(tmp_path).run(sync=False)

    assert b"Fixed `\r\n` in zshrc." in note.read_bytes()
