from pathlib import Path

from config.settings import Config
from src.agents.sync_agent import AutographSyncAgent
from src.core.daily_note_renderer import retrofit_daily_note
from src.core.vocabulary import ConceptIndex


class DailyNoteRetrofitAgent:
    """Add properties, tags and wiki links to existing generated daily notes."""

    generated_marker = "*Generated by Autograph Agent*"

    def __init__(self, vault_root: Path = None):
        self.vault_root = Path(vault_root or Config.VAULT_ROOT)
        self.sync_agent = AutographSyncAgent(self.vault_root)

    def run(self, sync: bool = True) -> int:
        concepts = ConceptIndex.load(self.vault_root)
        updated = 0
        for note_path in sorted((self.vault_root / "daily_notes").glob("*.md")):
            # newline="" keeps a stray "\r\n" the model wrote into prose as is.
            with open(note_path, encoding="utf-8", errors="replace", newline="") as note:
                content = note.read()
            if self.generated_marker not in content:
                continue
            try:
                new_content = retrofit_daily_note(content, note_path.stem, concepts.annotate)
            except ValueError as error:
                print(f"⚠️ Skipped {note_path.name}: {error}")
                continue
            if new_content != content:
                with open(note_path, "w", encoding="utf-8", newline="") as note:
                    note.write(new_content)
                updated += 1

        print(f"🏷️ Updated properties on {updated} generated daily notes.")
        if updated and sync:
            self.sync_agent.sync()
        return updated
